def load(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def save(path, data):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")

def prepend_news(rel, item):
    path = os.path.join(BASE, rel)
    d = load(path)
    d["news"] = [item] + d["news"]
    if len(d["news"]) > 8:
        d["news"] = d["news"][:8]
    d["updated"] = TODAY
    save(path, d)
    return path

