def parse_t(s):
    # "8/25 20时" / "8/25 17时(预报)" / "8/28白天 登陆(预报)"
    m = re.search(r"(\d+)/(\d+)\s*(?:(\d+)时|白天)?", s)
    if not m:
        return (0, 0, 0)
    mo, da, hr = int(m.group(1)), int(m.group(2)), m.group(3)
    if hr is None:
        hr = 12 if "白天" in s else 0
    return (mo, da, int(hr))

